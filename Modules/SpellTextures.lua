-- 获取玩家当前职业
local _, playerClass = UnitClass("player")

-------------------------------------------------------------------------------
-- API：根据技能名称获取对应的贴图路径
-------------------------------------------------------------------------------
function Addon.Spells.GetTextureForSpell(spellName)
    if spellName and playerClass then
        local classSpells = Addon.Spells.ClassSpellTextures[playerClass]
        if classSpells then
            -- 中文客户端直接命中；英文客户端则通过职业专属别名命中同一张中文贴图。
            local texture = classSpells[spellName]
            if not texture and Addon.Spells.EnglishSpellAliases then
                local aliases = Addon.Spells.EnglishSpellAliases[playerClass]
                local chineseName = aliases and aliases[spellName]
                texture = chineseName and classSpells[chineseName]
            end
            if texture then
                return Addon.ResolveCardFrontTexture and Addon:ResolveCardFrontTexture(texture) or texture
            end
        end
    end
    return Addon.Spells.DEFAULT_TEXTURE
end

-- Keep the Warlock trigger map aligned with the authoritative card catalogue.
-- The installed card set is the 102-name list in CardCatalog.lua, and every
-- entry points directly to the matching file in the Warlock texture folder.
do
    local catalog = Addon.CardCatalog and Addon.CardCatalog[1]
    local warlock = catalog and catalog.classes and catalog.classes.WARLOCK
    if warlock and warlock.names then
        local actual = {}
        for _, spellName in ipairs(warlock.names) do
            actual[spellName] = "Interface\\AddOns\\CardMaster\\Textures\\Cardfront\\cardfront1\\Warlock\\" .. spellName .. ".blp"
        end
        Addon.Spells.ClassSpellTextures.WARLOCK = actual
    end
end

-------------------------------------------------------------------------------
-- API：随机抽取当前职业库中的一张贴图
-------------------------------------------------------------------------------
function Addon.Spells.GetRandomTexture()
    if playerClass then
        local classSpells = Addon.Spells.ClassSpellTextures[playerClass]
        if classSpells then
            local list = {}
            for _, path in pairs(classSpells) do
                table.insert(list, path)
            end
            if #list > 0 then
                local texture = list[math.random(1, #list)]
                return Addon.ResolveCardFrontTexture and Addon:ResolveCardFrontTexture(texture) or texture
            end
        end
    end
    return Addon.Spells.DEFAULT_TEXTURE
end
