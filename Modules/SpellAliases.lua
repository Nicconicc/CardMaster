-- Collection cards are stored under their Chinese artwork names.  Build a
-- stable reverse lookup for the English UI: when several aliases refer to the
-- same card, prefer the shortest name and then alphabetical order.  This
-- selects the canonical-looking spell label without changing trigger aliases.
do
    local displayNames = {}
    for classToken, aliases in pairs(Addon.Spells.EnglishSpellAliases) do
        local names = {}
        for englishName, chineseName in pairs(aliases) do
            local current = names[chineseName]
            if not current or #englishName < #current or (#englishName == #current and englishName < current) then
                names[chineseName] = englishName
            end
        end
        displayNames[classToken] = names
    end
    Addon.Spells.CardDisplayEnglish = displayNames
end
